# ============================================================
# 5. 이미지 전처리
# ============================================================
#
# 이미지의 너무 작은 노이즈를 줄이기 위한 함수.
#
# Gaussian Blur를 사용해 색상 분석이 조금 더 안정적으로
# 이루어지도록 한다.
# ============================================================


def preprocess_image(image):

    if image is None:
        return None

    try:

        blurred = cv2.GaussianBlur(
            image,
            (5, 5),
            0
        )

        return blurred

    except Exception:

        return image


# ============================================================
# 6. 이미지에서 색상별 비율 계산
# ============================================================
#
# 전체 이미지에서 각 색상이 얼마나 차지하는지 계산한다.
#
# 예:
#
# red    : 0.52
# orange : 0.08
# yellow : 0.03
# ...
#
# 이런 식으로 계산한 뒤 가장 높은 색상을 대표 색상으로
# 선택한다.
# ============================================================


def calculate_color_scores(image):

    if image is None:
        return {}

    processed_image = preprocess_image(image)

    if processed_image is None:
        return {}

    hsv = cv2.cvtColor(
        processed_image,
        cv2.COLOR_BGR2HSV
    )

    scores = {}

    total_pixels = hsv.shape[0] * hsv.shape[1]

    if total_pixels <= 0:
        return {}

    for color_name, ranges in HSV_RANGES.items():

        combined_mask = np.zeros(
            hsv.shape[:2],
            dtype=np.uint8
        )

        for lower, upper in ranges:

            mask = cv2.inRange(
                hsv,
                lower,
                upper
            )

            combined_mask = cv2.bitwise_or(
                combined_mask,
                mask
            )

        matching_pixels = cv2.countNonZero(
            combined_mask
        )

        ratio = (
            matching_pixels
            / total_pixels
        )

        scores[color_name] = ratio

    return scores


# ============================================================
# 7. 대표 색상 결정
# ============================================================
#
# 가장 높은 비율을 가진 색상을 선택한다.
#
# 단, 모든 색상 비율이 지나치게 낮으면
# "unknown"으로 처리한다.
#
# 이는 사진 전체가 흰색 배경인 경우처럼
# 실제 음료 색상이 제대로 잡히지 않는 상황을
# 어느 정도 방지하기 위한 것이다.
# ============================================================


def detect_dominant_color(image):

    scores = calculate_color_scores(image)

    if not scores:
        return "unknown"

    dominant_color = max(
        scores,
        key=scores.get
    )

    dominant_score = scores[dominant_color]

    # --------------------------------------------------------
    # 최소 색상 비율
    #
    # 사진 전체에서 특정 색상이 너무 적으면
    # 확실한 색상이라고 보기 어렵다.
    # --------------------------------------------------------

    MIN_COLOR_RATIO = 0.03

    if dominant_score < MIN_COLOR_RATIO:
        return "unknown"

    return dominant_color


# ============================================================
# 8. 색상 분석 결과 생성
# ============================================================
#
# Flask에서 사용하기 편하도록 결과를 dictionary 형태로
# 만들어준다.
#
# 반환 예시:
#
# {
#     "ok": True,
#     "color": "brown",
#     "color_name": "갈색",
#     "emoji": "🟤",
#     "score": 0.43,
#     "drinks": [
#         "커피",
#         "홍차",
#         "콜라"
#     ]
# }
# ============================================================


def analyze_image(image):

    if image is None:

        return {
            "ok": False,
            "color": "unknown",
            "color_name": "분석 실패",
            "emoji": "❓",
            "score": 0,
            "drinks": [],
            "message": "이미지를 읽을 수 없습니다.",
        }

    scores = calculate_color_scores(
        image
    )

    if not scores:

        return {
            "ok": False,
            "color": "unknown",
            "color_name": "분석 실패",
            "emoji": "❓",
            "score": 0,
            "drinks": [],
            "message": "이미지 색상을 분석할 수 없습니다.",
        }

    dominant_color = max(
        scores,
        key=scores.get
    )

    dominant_score = scores[
        dominant_color
    ]

    MIN_COLOR_RATIO = 0.03

    if dominant_score < MIN_COLOR_RATIO:

        return {
            "ok": False,
            "color": "unknown",
            "color_name": "알 수 없음",
            "emoji": "❓",
            "score": round(
                dominant_score * 100,
                2
            ),
            "drinks": [],
            "message": (
                "뚜렷한 음료 색상을 찾지 못했습니다. "
                "음료가 잘 보이는 사진을 사용해주세요."
            ),
        }

    return {
        "ok": True,

        "color": dominant_color,

        "color_name": COLOR_NAMES.get(
            dominant_color,
            dominant_color
        ),

        "emoji": COLOR_EMOJIS.get(
            dominant_color,
            "🥤"
        ),

        "score": round(
            dominant_score * 100,
            2
        ),

        "drinks": DRINKS_BY_COLOR.get(
            dominant_color,
            []
        ),

        "message": (
            f"{COLOR_NAMES.get(dominant_color, dominant_color)} "
            "색상의 음료로 분석되었습니다."
        ),
    }


